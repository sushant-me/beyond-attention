"""Do the prosody descriptors separate synthetic conditions that differ in prosody?

This is the honest version of the question an affect front-end is usually asked
to answer. The usual version -- "does it recognise emotion?" -- cannot be
answered here: there is no labelled emotional speech in this repository, and
inventing labels for signals this file synthesised would be circular. So the
question is narrowed to something that *can* be measured:

    Build utterances that differ **only** in the four prosodic axes the front
    end claims to measure -- F0 level, F0 spread, energy spread, and rate --
    and ask whether the descriptors recover the condition they were generated
    from, out of four, with a chance baseline and controls.

Two things follow from that framing, and both are stated in the README:

* A high accuracy is a check that the front end carries the axes it was built
  to carry. It is **not** evidence that emotion is decodable from speech,
  because the conditions were designed to be separable and the labels come from
  the generator, not from a listener.
* A low accuracy would be a real failure, and would mean the descriptors are not
  measuring what the synthesis varied.

The classifier is deliberately the weakest one that can express the question: a
leave-one-out nearest-centroid rule in z-scored descriptor space, refitting the
scaling on each training fold so nothing leaks from the held-out utterance.
Chance is 1/4.

Controls, because this repository has already published one headline that a
control falsified:

* **Label shuffle** -- the identical classifier on permuted labels. This
  establishes the chance baseline empirically rather than assuming 1/4.
* **Two conditions with identical parameters** -- same generator call, different
  RNG stream. Nothing was manipulated between them, so a classifier that
  separates them is measuring something other than the axes; this control is
  the one that can fail in the dangerous direction.
* **White noise through the voiced/unvoiced decision** -- a detector that always
  answers "voiced" passes every tone test in `tests/test_voice.py`.
* **F0 recovery against the generator's own target** -- the descriptor is
  checked against the number the synthesiser was asked for.

    python -u experiments/voice_affect.py --out voice-affect.json
"""

from __future__ import annotations

import argparse
import json
import time
from dataclasses import asdict, dataclass
from pathlib import Path

import numpy as np

from beyond_attention.voice import (
    VOICED_PEAK_THRESHOLD,
    VoiceEncoder,
    affect_descriptors,
    frame_features,
    waveform_to_model_input,
)

# Descriptors used for classification. `n_frames` and `duration_s` are excluded
# because they are design constants of the synthesis (every utterance is the
# same length), so including them would add two columns that cannot carry
# information and would flatter every accuracy below.
CLUSTER_FEATURES = (
    "f0_mean", "f0_std", "f0_range", "jitter", "jitter_relative",
    "energy_mean", "energy_std", "energy_mean_voiced", "energy_std_voiced",
    "energy_flux_mean", "voiced_ratio",
    "speaking_rate", "zcr_mean", "centroid_mean", "flatness_mean",
)

# The four synthetic conditions. Each utterance is generated by one function
# with one parameter tuple, so "the conditions differ only in these four axes"
# is literally true of the code path, not an assertion about it.
@dataclass(frozen=True)
class Condition:
    name: str
    f0_base: float        # Hz, the pitch level
    f0_swing: float       # relative depth of the within-burst pitch movement
    f0_jitter: float      # relative random pitch offset per burst
    amp_var: float        # relative spread of burst amplitudes
    bursts_per_sec: float
    duty: float = 0.6     # fraction of each burst slot that is voiced


CONDITIONS = (
    # A steady, low-spread, slow, even delivery: the "monotone" corner.
    Condition("neutral", f0_base=150.0, f0_swing=0.010, f0_jitter=0.010,
              amp_var=0.03, bursts_per_sec=2.0),
    # High pitch level, large pitch movement, large loudness movement, fast.
    Condition("aroused", f0_base=225.0, f0_swing=0.120, f0_jitter=0.050,
              amp_var=0.45, bursts_per_sec=5.0),
    # Low, slow, even, quiet-relative-to-mean: the opposite corner.
    Condition("subdued", f0_base=110.0, f0_swing=0.004, f0_jitter=0.010,
              amp_var=0.05, bursts_per_sec=1.0),
    # High and unsteady, but not loud: pitch spread without energy spread.
    Condition("unsteady", f0_base=255.0, f0_swing=0.150, f0_jitter=0.100,
              amp_var=0.15, bursts_per_sec=3.5),
)

VIBRATO_HZ = 4.0  # rate of the within-burst pitch movement


def synthesise(
    condition: Condition, seconds: float, sample_rate: int, rng: np.random.Generator
) -> np.ndarray:
    """Render one utterance. Amplitudes are in arbitrary units, peak ~0.4."""
    n_samples = int(round(seconds * sample_rate))
    signal = np.zeros(n_samples)
    n_bursts = max(1, int(round(condition.bursts_per_sec * seconds)))
    slot = n_samples / n_bursts

    for i in range(n_bursts):
        start = int(round(i * slot))
        stop = min(n_samples, start + int(round(slot * condition.duty)))
        if stop <= start:
            continue
        local = np.arange(stop - start) / sample_rate
        # Two independent sources of pitch spread: a smooth movement inside the
        # burst (what "vibrato" is) and a per-burst offset (what "unsteady"
        # between bursts is). Both are in the descriptor `f0_std`.
        pitch = condition.f0_base * (1.0 + condition.f0_jitter
                                     * rng.standard_normal())
        phase = 2 * np.pi * pitch * (
            local + condition.f0_swing / (2 * np.pi * VIBRATO_HZ)
            * np.sin(2 * np.pi * VIBRATO_HZ * local)
        )
        amplitude = 0.4 * max(0.05, 1.0 + condition.amp_var
                              * rng.standard_normal())
        signal[start:stop] = amplitude * np.sin(phase)
    return signal


# --------------------------------------------------------------------------
# The classifier: the weakest one that can express the question
# --------------------------------------------------------------------------

def _zscore(train: np.ndarray, test: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    mean = train.mean(axis=0)
    std = train.std(axis=0)
    std[std == 0.0] = 1.0
    return (train - mean) / std, (test - mean) / std


def leave_one_out_accuracy(
    features: np.ndarray, labels: np.ndarray, columns: list[int] | None = None
) -> tuple[float, list[list[int]]]:
    """Nearest-centroid, one held-out utterance at a time, scaling refit per fold.

    Returns the accuracy and the confusion matrix (rows true, columns predicted).
    """
    matrix = features if columns is None else features[:, columns]
    classes = sorted(set(labels.tolist()))
    index = {label: i for i, label in enumerate(classes)}
    confusion = [[0] * len(classes) for _ in classes]
    correct = 0

    for held_out in range(matrix.shape[0]):
        mask = np.ones(matrix.shape[0], dtype=bool)
        mask[held_out] = False
        train_z, test_z = _zscore(matrix[mask], matrix[held_out][None, :])
        centroids = np.stack([
            train_z[labels[mask] == label].mean(axis=0) for label in classes
        ])
        distances = np.linalg.norm(centroids - test_z, axis=1)
        predicted = classes[int(np.argmin(distances))]
        confusion[index[labels[held_out]]][index[predicted]] += 1
        correct += int(predicted == labels[held_out])
    return correct / matrix.shape[0], confusion


def shuffle_control(
    features: np.ndarray, labels: np.ndarray, rounds: int, seed: int
) -> dict[str, float]:
    """The same classifier on permuted labels: an empirical chance baseline."""
    rng = np.random.default_rng(seed)
    scores = [
        leave_one_out_accuracy(features, rng.permutation(labels))[0]
        for _ in range(rounds)
    ]
    values = np.array(scores)
    return {
        "rounds": float(rounds),
        "mean": float(values.mean()),
        "p95": float(np.percentile(values, 95)),
        "max": float(values.max()),
    }


def z_above_chance(accuracy: float, n: int, chance: float) -> float:
    """Normal-approximation z of an accuracy against chance.

    Reported next to every accuracy because "0.562 against 0.500" sounds like a
    result and, at 32 leave-one-out samples, is 0.7 standard deviations -- noise.
    The approximation ignores the correlation between folds; the label-shuffle
    control is the empirical version of the same number and is what should be
    believed when the two disagree.
    """
    return (accuracy - chance) / float(np.sqrt(chance * (1.0 - chance) / n))


def separation(
    features: np.ndarray, labels: np.ndarray, columns: list[int]
) -> dict[str, float]:
    """How far apart the condition centroids are, in units of within-condition spread.

    A single accuracy of 1.000 hides whether the classes were barely separated or
    separated by a mile. This reports the ratio of the smallest centroid-to-
    centroid distance to the mean within-condition spread, so "by how much" has
    a number attached to it.
    """
    matrix = features[:, columns]
    mean = matrix.mean(axis=0)
    std = matrix.std(axis=0)
    std[std == 0.0] = 1.0
    matrix = (matrix - mean) / std

    classes = sorted(set(labels.tolist()))
    centroids = np.stack([
        matrix[labels == label].mean(axis=0) for label in classes
    ])
    within = float(np.mean([
        np.linalg.norm(matrix[labels == label] - centroids[i], axis=1).mean()
        for i, label in enumerate(classes)
    ]))
    between = min(
        float(np.linalg.norm(centroids[i] - centroids[j]))
        for i in range(len(classes))
        for j in range(i + 1, len(classes))
    )
    return {
        "within_spread": within,
        "closest_centroids": between,
        "ratio": between / within if within > 0 else float("inf"),
    }


# --------------------------------------------------------------------------

def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--utterances", type=int, default=16,
                        help="utterances per condition")
    parser.add_argument("--duration", type=float, default=2.0)
    parser.add_argument("--sample-rate", type=int, default=16_000)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--shuffle-rounds", type=int, default=200)
    parser.add_argument("--out", default="voice-affect.json")
    args = parser.parse_args()

    started = time.perf_counter()
    rng = np.random.default_rng(args.seed)

    # --- generate ---------------------------------------------------------
    names: list[str] = []
    parameters: dict[str, dict] = {}
    raw: list[np.ndarray] = []
    for condition in CONDITIONS:
        parameters[condition.name] = asdict(condition)
        for _ in range(args.utterances):
            raw.append(synthesise(condition, args.duration,
                                  args.sample_rate, rng))
            names.append(condition.name)

    # --- measure ----------------------------------------------------------
    summaries = [
        affect_descriptors(frame_features(x, args.sample_rate)) for x in raw
    ]
    descriptor_names = list(summaries[0])
    features = np.array(
        [[summary[name] for name in descriptor_names] for summary in summaries]
    )
    labels = np.array(names)
    columns = [descriptor_names.index(name) for name in CLUSTER_FEATURES]
    classes = [condition.name for condition in CONDITIONS]

    per_condition = {
        name: {
            "descriptors": {
                key: float(np.mean([
                    summaries[i][key]
                    for i in range(len(summaries)) if labels[i] == name
                ]))
                for key in ("f0_mean", "f0_std", "energy_mean", "energy_std",
                            "energy_mean_voiced", "energy_std_voiced",
                            "energy_flux_mean", "voiced_ratio", "speaking_rate",
                            "jitter", "flatness_mean")
            },
            "parameters": parameters[name],
        }
        for name in classes
    }

    accuracy, confusion = leave_one_out_accuracy(features, labels, columns)
    separation_stats = separation(features, labels, columns)

    # Each descriptor alone, so the table shows which axis carries which
    # distinction instead of only the aggregate.
    single: dict[str, dict[str, float]] = {}
    for name in CLUSTER_FEATURES:
        column = [descriptor_names.index(name)]
        score, _ = leave_one_out_accuracy(features, labels, column)
        single[name] = {"accuracy": score}

    # --- controls ---------------------------------------------------------
    shuffled = shuffle_control(features, labels, args.shuffle_rounds, args.seed)

    # Two conditions from the *same* parameter tuple and different RNG streams.
    twin = CONDITIONS[0]
    twin_labels: list[str] = []
    twin_raw: list[np.ndarray] = []
    for _ in range(args.utterances):
        twin_raw.append(synthesise(twin, args.duration, args.sample_rate, rng))
        twin_labels.append("twin_a")
        twin_raw.append(synthesise(twin, args.duration, args.sample_rate, rng))
        twin_labels.append("twin_b")
    twin_features = np.array([
        [affect_descriptors(frame_features(x, args.sample_rate))[name]
         for name in descriptor_names]
        for x in twin_raw
    ])
    twin_accuracy, _ = leave_one_out_accuracy(
        twin_features, np.array(twin_labels), columns
    )

    # White noise through the voiced/unvoiced decision. The threshold and the
    # observed margin are both reported, so a reader can see how close it was.
    noise_rng = np.random.default_rng(args.seed + 10_000)
    noise_ratios: list[float] = []
    noise_confidences: list[float] = []
    for _ in range(8):
        noise = 0.3 * noise_rng.standard_normal(args.sample_rate)
        noise_features = frame_features(noise, args.sample_rate)
        noise_ratios.append(
            affect_descriptors(noise_features)["voiced_ratio"]
        )
        noise_confidences.append(float(noise_features.voiced_confidence.max()))

    # F0 recovery against the generator's own target. Only the burst-level
    # jitter moves the true mean, so the target compared against is the base
    # pitch before the per-burst offsets -- an approximation, stated as such.
    errors = [
        abs(per_condition[name]["descriptors"]["f0_mean"]
            / per_condition[name]["parameters"]["f0_base"] - 1.0) * 100.0
        for name in classes
    ]

    # --- the bridge is exercised, not just imported -----------------------
    bridge = waveform_to_model_input(raw[0], args.sample_rate, d_model=32)
    encoder = VoiceEncoder(32, seed=args.seed)
    encode_delta = float(np.abs(
        encoder.encode(frame_features(raw[0], args.sample_rate))
        - encoder.encode(frame_features(raw[1], args.sample_rate))
    ).max())

    payload = {
        "config": {
            "sample_rate": args.sample_rate,
            "duration_s": args.duration,
            "utterances_per_condition": args.utterances,
            "seed": args.seed,
            "shuffle_rounds": args.shuffle_rounds,
            "classifier": "leave-one-out nearest centroid, z-scored per fold",
            "chance": 1.0 / len(classes),
            "cluster_features": list(CLUSTER_FEATURES),
            "bridge_output_shape": list(bridge.shape),
        },
        "conditions": per_condition,
        "separability": {
            "accuracy": accuracy,
            "chance": 1.0 / len(classes),
            "n_utterances": int(features.shape[0]),
            "z_vs_chance": z_above_chance(
                accuracy, features.shape[0], 1.0 / len(classes)
            ),
            "confusion": confusion,
            "classes": classes,
            **separation_stats,
        },
        "single_descriptor": single,
        "controls": {
            "label_shuffle": shuffled,
            "identical_parameters": {
                "accuracy": twin_accuracy,
                "chance": 0.5,
                "n_utterances": len(twin_labels),
                "z_vs_chance": z_above_chance(
                    twin_accuracy, len(twin_labels), 0.5
                ),
                "note": ("same Condition tuple, different RNG stream; nothing "
                         "was manipulated between the two groups"),
            },
            "white_noise_voicing": {
                "voiced_ratio_mean": float(np.mean(noise_ratios)),
                "voiced_ratio_max": float(np.max(noise_ratios)),
                "max_confidence": float(np.max(noise_confidences)),
                "threshold": VOICED_PEAK_THRESHOLD,
            },
            "f0_recovery": {
                "mean_abs_error_pct": float(np.mean(errors)),
                "worst_abs_error_pct": float(np.max(errors)),
                "note": ("descriptor f0_mean against the generator's base pitch; "
                         "per-burst jitter moves the true mean, so this bounds "
                         "the error rather than measuring it exactly"),
            },
            "encoder_separates_two_utterances": encode_delta,
        },
        "wall_seconds": round(time.perf_counter() - started, 2),
    }

    Path(args.out).write_text(json.dumps(payload, indent=2))

    # --- human-readable summary ------------------------------------------
    print(f"{features.shape[0]} utterances, "
          f"{args.utterances} per condition, {args.duration}s each")
    print()
    header = f"{'condition':<12}{'f0_mean':>9}{'f0_std':>8}{'energy_std':>11}" \
             f"{'rate':>7}{'jitter':>8}"
    print(header)
    for name in classes:
        d = per_condition[name]["descriptors"]
        print(f"{name:<12}{d['f0_mean']:>9.1f}{d['f0_std']:>8.2f}"
              f"{d['energy_std']:>11.4f}{d['speaking_rate']:>7.2f}"
              f"{d['jitter']:>8.3f}")
    print()
    print(f"leave-one-out nearest centroid: {accuracy:.3f} "
          f"(chance {1.0 / len(classes):.3f}, n={features.shape[0]}, "
          f"{z_above_chance(accuracy, features.shape[0], 1.0 / len(classes)):+.1f}"
          f" sigma)")
    print(f"closest centroids {separation_stats['closest_centroids']:.2f} "
          f"vs within-condition spread {separation_stats['within_spread']:.2f} "
          f"= {separation_stats['ratio']:.1f}x")
    print("confusion (rows true, columns predicted), "
          f"classes {classes}:")
    for name, row in zip(classes, confusion):
        print(f"  {name:<12}{row}")
    print()
    print("single descriptor alone:")
    for name, row in single.items():
        print(f"  {name:<20}{row['accuracy']:.3f}")
    print()
    print("controls:")
    print(f"  label shuffle ({shuffled['rounds']:.0f} rounds): "
          f"mean {shuffled['mean']:.3f}, p95 {shuffled['p95']:.3f}, "
          f"max {shuffled['max']:.3f}")
    print(f"  identical parameters, 2 groups: {twin_accuracy:.3f} "
          f"(chance 0.500, "
          f"{z_above_chance(twin_accuracy, len(twin_labels), 0.5):+.1f} sigma)")
    print(f"  white noise: voiced_ratio max {np.max(noise_ratios):.3f}, "
          f"max confidence {np.max(noise_confidences):.3f} "
          f"(threshold {VOICED_PEAK_THRESHOLD})")
    print(f"  f0 recovery vs generator: mean {np.mean(errors):.2f}%, "
          f"worst {np.max(errors):.2f}%")
    print(f"  bridge output {tuple(bridge.shape)}, "
          f"encoder differs by {encode_delta:.4f} between utterances")
    print(f"\nwrote {args.out} in {payload['wall_seconds']}s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
